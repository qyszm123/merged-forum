  Object.assign(BANKS, BANKS_EXT)
  Object.assign(TASKS, TASKS_EXT)

  const byTask = {}
  let total = 0
  for (const [pathId, tasks] of Object.entries(TASKS)) {
    for (const task of tasks) {
      const bank = buildTaskBank(pathId, task)
      byTask[`${pathId}:${task.id}`] = bank
      total += bank.length
    }
  }
  const missing = Object.keys(BANKS).filter((k) => !(BANKS[k] && BANKS[k].length))
  if (missing.length) throw new Error('empty banks: ' + missing.join(','))

  const root = path.join(__dirname, '../..')
  const browserOut = path.join(root, 'train-question-banks.js')
  const moduleOut = path.join(__dirname, '../src/data/trainQuestionBanks.js')
  // 浏览器不再下发题库（含答案）；仅保留服务端模块。若文件存在则写空壳提示。
