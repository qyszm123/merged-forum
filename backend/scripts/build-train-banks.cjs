function buildTaskBank(pathId, task) {
  const comps = chapterComprehensives()
  const bank = []
  const nodes = (task.nodes || []).filter((n) => n.type === 'quiz')
  nodes.forEach((n) => {
    const list = BANKS[n.id] || []
    list.forEach((q) => bank.push({ ...q }))
  })
  const comp = comps[task.id]
  if (comp) {
    // 综合题挂到本章每个 quiz 知识点，保证单关刷题也能抽到章综合
    nodes.forEach((n) => {
      bank.push({ ...comp, id: `${comp.id}-${n.id}`, kpId: n.id })
    })
  }
  return bank
}

