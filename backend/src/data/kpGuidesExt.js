function quizGuide(name, q, opts, ai) {
  return {
    desc: `答对通关。本节对应「${name}」。不会就打开攻略视频或让 AI 讲。`,
    quiz: { q, opts },
    guide: [],
    ai
  }
}

function workGuide(name, ai) {
  return {
    desc: `完成本节「${name}」作品任务即可通关。不会就看攻略视频或 AI。`,
    work: true,
    guide: [],
    ai
  }
}

function innovGuide(unitHint) {
  return workGuide(
    '再设计与微创新',
    `在「${unitHint}」基础上做一次小改进：换场景、加功能或优化体验，写清改了什么、为什么更好。`
  )
}

function rewardGuide(title, q, opts, ai) {
  return {
    desc: `综合通关：确认已完成全部单元后领取「${title}」。`,
    quiz: { q, opts },
    guide: [],
    ai
  }
}

